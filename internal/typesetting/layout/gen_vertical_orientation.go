//go:build ignore

// gen_vertical_orientation writes vertical_orientation.go, the table of the characters that
// vertical text keeps upright, from the Unicode Character Database's VerticalOrientation.txt
// (UAX #50). It downloads the file of ucdVersion into the path given, if it is not there yet.
// go generate runs it, from this directory.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// ucdVersion is the version of Unicode the table follows.
const ucdVersion = "16.0.0"

// ucdURL is where VerticalOrientation.txt of ucdVersion is: the Unicode Consortium's own tools
// repository, as unicode.org's web server refuses some hosts.
const ucdURL = "https://raw.githubusercontent.com/unicode-org/unicodetools/main/unicodetools/data/ucd/" + ucdVersion + "/VerticalOrientation.txt"

// classNames are the values of Vertical_Orientation other than R (rotated, the default), by
// their names in vertical.go.
var classNames = map[string]string{"U": "orientationUpright", "Tu": "orientationTransformedUpright", "Tr": "orientationTransformedRotated"}

// codeRange is a range of code points of one class, both ends included.
type codeRange struct {
	low, high rune
	class     string
}

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: gen_vertical_orientation <VerticalOrientation.txt> <output.go>")
	}
	source, output := os.Args[1], os.Args[2]
	if err := download(source); err != nil {
		log.Fatal(err)
	}
	ranges, err := readRanges(source)
	if err != nil {
		log.Fatal(err)
	}
	var code bytes.Buffer
	fmt.Fprintf(&code, "// Code generated by gen_vertical_orientation.go from VerticalOrientation-%s.txt. DO NOT EDIT.\n\n", ucdVersion)
	fmt.Fprintf(&code, "package layout\n\n")
	fmt.Fprintf(&code, "// verticalOrientations are the ranges of characters whose Vertical_Orientation is not R, in\n")
	fmt.Fprintf(&code, "// order, from Unicode %s.\n", ucdVersion)
	fmt.Fprintf(&code, "var verticalOrientations = [...]orientationRange{\n")
	for _, found := range ranges {
		fmt.Fprintf(&code, "\t{0x%04X, 0x%04X, %s},\n", found.low, found.high, classNames[found.class])
	}
	fmt.Fprintf(&code, "}\n")
	formatted, err := format.Source(code.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(output, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

// download fetches VerticalOrientation.txt into path, unless it is there already.
func download(path string) error {
	if _, err := os.Stat(path); err == nil {
		return nil
	}
	response, err := http.Get(ucdURL)
	if err != nil {
		return err
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return fmt.Errorf("%s: %s", ucdURL, response.Status)
	}
	data, err := io.ReadAll(response.Body)
	if err != nil {
		return err
	}
	if !bytes.Contains(data, []byte("VerticalOrientation-"+ucdVersion+".txt")) {
		return fmt.Errorf("%s: not VerticalOrientation-%s.txt", ucdURL, ucdVersion)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

// readRanges returns the ranges of the file whose class is not R, adjacent ranges of a class
// merged.
func readRanges(path string) ([]codeRange, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	var ranges []codeRange
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line, _, _ := strings.Cut(scanner.Text(), "#")
		codes, class, ok := strings.Cut(line, ";")
		if !ok {
			continue
		}
		class = strings.TrimSpace(class)
		if _, kept := classNames[class]; !kept {
			if class != "R" {
				return nil, fmt.Errorf("unknown class %q", class)
			}
			continue
		}
		lowText, highText, isRange := strings.Cut(strings.TrimSpace(codes), "..")
		if !isRange {
			highText = lowText
		}
		low, err := strconv.ParseUint(lowText, 16, 32)
		if err != nil {
			return nil, err
		}
		high, err := strconv.ParseUint(highText, 16, 32)
		if err != nil {
			return nil, err
		}
		if last := len(ranges) - 1; last >= 0 && ranges[last].class == class && ranges[last].high+1 == rune(low) {
			ranges[last].high = rune(high)
			continue
		}
		if last := len(ranges) - 1; last >= 0 && ranges[last].high >= rune(low) {
			return nil, fmt.Errorf("%s: ranges out of order at %s", path, codes)
		}
		ranges = append(ranges, codeRange{low: rune(low), high: rune(high), class: class})
	}
	return ranges, scanner.Err()
}
